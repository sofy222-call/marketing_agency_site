// =========================================
// CHANGE LANGUAGE
// =========================================

export function setLanguage(language) {

  if (!translations[language]) {

    language = 'en'

  }


  currentLanguage =
    language


  localStorage.setItem(
    'siteLanguage',
    language
  )


  document.documentElement.lang =
    language === 'kz'
      ? 'kk'
      : language


  if (
    document.body.classList.contains(
      'profile-body'
    )
  ) {

    translateProfilePage()

  } else {

    translateMainPage()

  }


  document
    .querySelectorAll('[data-lang]')
    .forEach(
      function (button) {

        button.classList.toggle(
          'is-active',
          button.dataset.lang === language
        )

      }
    )


  window.dispatchEvent(
    new CustomEvent(
      'languagechange',
      {
        detail: {
          language
        }
      }
    )
  )

}



// =========================================
// INITIALIZE
// =========================================

export function initI18n() {

  document
    .querySelectorAll('[data-lang]')
    .forEach(
      function (button) {

        button.addEventListener(
          'click',
          function () {

            setLanguage(
              button.dataset.lang
            )

          }
        )

      }
    )


  setLanguage(
    currentLanguage
  )

}